-- Schreibbot v90: repaired virtual coin bank + PIN protected player transfers.
-- Run once in the Supabase SQL editor of the existing Schreibbot project.
-- Coins remain virtual and cannot be purchased, redeemed or paid out.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.online_slot_bank_accounts (
  player_id uuid primary key references auth.users(id) on delete cascade,
  bank_balance bigint not null default 0,
  bank_day date not null default (now() at time zone 'Europe/Berlin')::date,
  deposited_today bigint not null default 0,
  bank_pin_hash text,
  pin_updated_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint online_slot_bank_accounts_balance_v90 check (bank_balance between 0 and 9000000000000000),
  constraint online_slot_bank_accounts_deposit_v90 check (deposited_today between 0 and 100000)
);

alter table public.online_slot_bank_accounts
  add column if not exists bank_pin_hash text,
  add column if not exists pin_updated_at timestamptz;

alter table public.online_slot_bank_accounts
  drop constraint if exists online_slot_bank_accounts_bank_balance_check,
  drop constraint if exists online_slot_bank_accounts_balance_v90,
  drop constraint if exists online_slot_bank_accounts_deposited_today_check,
  drop constraint if exists online_slot_bank_accounts_deposit_v90;

alter table public.online_slot_bank_accounts
  add constraint online_slot_bank_accounts_balance_v90 check (bank_balance between 0 and 9000000000000000),
  add constraint online_slot_bank_accounts_deposit_v90 check (deposited_today between 0 and 100000);

alter table public.online_slot_bank_accounts enable row level security;
revoke all on table public.online_slot_bank_accounts from public, anon, authenticated;

create table if not exists public.online_slot_bank_pin_attempts (
  player_id uuid primary key references auth.users(id) on delete cascade,
  failed_count integer not null default 0 check (failed_count between 0 and 5),
  window_started_at timestamptz not null default now(),
  locked_until timestamptz,
  updated_at timestamptz not null default now()
);
alter table public.online_slot_bank_pin_attempts enable row level security;
revoke all on table public.online_slot_bank_pin_attempts from public, anon, authenticated;

create table if not exists public.online_slot_bank_transfers (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  gross_amount bigint not null check (gross_amount > 0),
  recipient_amount bigint not null check (recipient_amount >= 0),
  fee_amount bigint not null default 0 check (fee_amount >= 0),
  transfer_mode text not null check (transfer_mode in ('instant','delayed')),
  status text not null default 'completed' check (status in ('pending','completed','refunded')),
  created_at timestamptz not null default now(),
  scheduled_for timestamptz,
  completed_at timestamptz,
  check (sender_id <> recipient_id)
);
create index if not exists online_slot_bank_transfers_sender_created_idx
  on public.online_slot_bank_transfers(sender_id, created_at desc);
create index if not exists online_slot_bank_transfers_recipient_created_idx
  on public.online_slot_bank_transfers(recipient_id, created_at desc);
create index if not exists online_slot_bank_transfers_due_idx
  on public.online_slot_bank_transfers(status, scheduled_for)
  where status = 'pending';

alter table public.online_slot_bank_transfers enable row level security;
revoke all on table public.online_slot_bank_transfers from public, anon, authenticated;

-- Recreate get_slot_bank with explicit aliases. This avoids PL/pgSQL output-column ambiguity.
drop function if exists public.get_slot_bank();
create function public.get_slot_bank()
returns table(
  wallet_balance bigint,
  bank_balance bigint,
  deposited_today bigint,
  daily_limit bigint,
  remaining_today bigint,
  pin_enabled boolean
)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_today date := (now() at time zone 'Europe/Berlin')::date;
  v_bank public.online_slot_bank_accounts%rowtype;
  v_wallet bigint := 0;
  v_pin boolean := false;
begin
  if v_uid is null then raise exception 'Bitte melde dich erneut an, um die Coin-Bank zu laden.'; end if;
  perform public.process_due_slot_bank_transfers();

  insert into public.online_slot_scores(player_id, display_name, total_points, spins, updated_at)
  values (v_uid, 'Spieler', 10, 0, now())
  on conflict (player_id) do nothing;

  insert into public.online_slot_bank_accounts(player_id, bank_day)
  values (v_uid, v_today)
  on conflict (player_id) do nothing;

  select b.* into v_bank
  from public.online_slot_bank_accounts as b
  where b.player_id = v_uid
  for update;

  if v_bank.bank_day <> v_today then
    update public.online_slot_bank_accounts as b
       set bank_day = v_today, deposited_today = 0, updated_at = now()
     where b.player_id = v_uid
     returning b.* into v_bank;
  end if;

  select coalesce(s.total_points, 0), (b.bank_pin_hash is not null)
    into v_wallet, v_pin
  from public.online_slot_scores as s
  join public.online_slot_bank_accounts as b on b.player_id = s.player_id
  where s.player_id = v_uid;

  return query
  select v_wallet,
         v_bank.bank_balance,
         v_bank.deposited_today,
         100000::bigint,
         greatest(0::bigint, 100000::bigint - v_bank.deposited_today),
         v_pin;
end;
$$;
revoke all on function public.get_slot_bank() from public, anon;
grant execute on function public.get_slot_bank() to authenticated;

-- Existing wallet <-> bank transfer, repaired by qualifying every column reference.
create or replace function public.transfer_slot_bank(p_action text, p_amount bigint)
returns table(action text, amount bigint, wallet_balance bigint, bank_balance bigint, deposited_today bigint, daily_limit bigint, remaining_today bigint)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_today date := (now() at time zone 'Europe/Berlin')::date;
  v_wallet public.online_slot_scores%rowtype;
  v_bank public.online_slot_bank_accounts%rowtype;
  v_limit constant bigint := 100000;
  v_max constant bigint := 9000000000000000;
begin
  if v_uid is null then raise exception 'Bitte melde dich erneut an, um Coins zu übertragen.'; end if;
  if p_action is null or p_action not in ('deposit', 'withdraw') then raise exception 'Unbekannte Bankaktion.'; end if;
  if p_amount is null or p_amount <= 0 or p_amount > 1000000000 then raise exception 'Bitte gib einen gültigen Coin-Betrag ein.'; end if;

  insert into public.online_slot_scores(player_id, display_name, total_points, spins, updated_at)
  values (v_uid, 'Spieler', 10, 0, now()) on conflict (player_id) do nothing;
  insert into public.online_slot_bank_accounts(player_id, bank_day)
  values (v_uid, v_today) on conflict (player_id) do nothing;

  select s.* into v_wallet from public.online_slot_scores as s where s.player_id = v_uid for update;
  select b.* into v_bank from public.online_slot_bank_accounts as b where b.player_id = v_uid for update;

  if v_bank.bank_day <> v_today then
    update public.online_slot_bank_accounts as b
       set bank_day = v_today, deposited_today = 0, updated_at = now()
     where b.player_id = v_uid returning b.* into v_bank;
  end if;

  if p_action = 'deposit' then
    if p_amount > (v_limit - v_bank.deposited_today) then
      raise exception 'Tageslimit erreicht: Pro Tag sind höchstens 100.000 Coins Einzahlung erlaubt.';
    end if;
    if p_amount > v_wallet.total_points then raise exception 'Du hast nicht genug Coins im Wallet.'; end if;
    if v_bank.bank_balance > v_max - p_amount then raise exception 'Die Coin-Bank hat ihr Speicherlimit erreicht.'; end if;
    update public.online_slot_scores as s
       set total_points = s.total_points - p_amount, updated_at = now()
     where s.player_id = v_uid returning s.* into v_wallet;
    update public.online_slot_bank_accounts as b
       set bank_balance = b.bank_balance + p_amount,
           deposited_today = b.deposited_today + p_amount,
           updated_at = now()
     where b.player_id = v_uid returning b.* into v_bank;
  else
    if p_amount > v_bank.bank_balance then raise exception 'In der Bank liegen nicht genug Coins.'; end if;
    if p_amount > (1000000000::bigint - v_wallet.total_points) then raise exception 'Das Wallet hat sein Speicherlimit erreicht.'; end if;
    update public.online_slot_bank_accounts as b
       set bank_balance = b.bank_balance - p_amount, updated_at = now()
     where b.player_id = v_uid returning b.* into v_bank;
    update public.online_slot_scores as s
       set total_points = s.total_points + p_amount, updated_at = now()
     where s.player_id = v_uid returning s.* into v_wallet;
  end if;

  return query
  select p_action, p_amount, v_wallet.total_points, v_bank.bank_balance,
         v_bank.deposited_today, v_limit,
         greatest(0::bigint, v_limit - v_bank.deposited_today);
end;
$$;
revoke all on function public.transfer_slot_bank(text, bigint) from public, anon;
grant execute on function public.transfer_slot_bank(text, bigint) to authenticated;

-- Six-digit PIN. The database stores a salted bcrypt hash, never the entered PIN.
create or replace function public.set_slot_bank_pin(p_new_pin text, p_current_pin text default null)
returns table(pin_enabled boolean, updated_at timestamptz)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_bank public.online_slot_bank_accounts%rowtype;
  v_now timestamptz := now();
begin
  if v_uid is null then raise exception 'Bitte melde dich erneut an.'; end if;
  if p_new_pin is null or p_new_pin !~ '^[0-9]{6}$' then raise exception 'Die Bank-PIN muss aus genau sechs Ziffern bestehen.'; end if;
  insert into public.online_slot_bank_accounts(player_id) values (v_uid) on conflict (player_id) do nothing;
  select b.* into v_bank from public.online_slot_bank_accounts as b where b.player_id = v_uid for update;
  if v_bank.bank_pin_hash is not null then
    if p_current_pin is null or p_current_pin !~ '^[0-9]{6}$' or crypt(p_current_pin, v_bank.bank_pin_hash) <> v_bank.bank_pin_hash then
      raise exception 'Die bisherige Bank-PIN ist nicht richtig.';
    end if;
  end if;
  update public.online_slot_bank_accounts as b
     set bank_pin_hash = crypt(p_new_pin, gen_salt('bf', 10)),
         pin_updated_at = v_now,
         updated_at = v_now
   where b.player_id = v_uid;
  delete from public.online_slot_bank_pin_attempts as a where a.player_id = v_uid;
  return query select true, v_now;
end;
$$;
revoke all on function public.set_slot_bank_pin(text, text) from public, anon;
grant execute on function public.set_slot_bank_pin(text, text) to authenticated;

-- Player-to-player transfer. Immediate: 5% fee to the unique Kamar303 bank account.
-- Delayed: funds are reserved immediately and credited after one hour with no fee.
create or replace function public.transfer_slot_bank_to_player(
  p_recipient_name text,
  p_amount bigint,
  p_pin text,
  p_mode text
)
returns table(
  transfer_id bigint,
  transfer_mode text,
  gross_amount bigint,
  recipient_amount bigint,
  fee_amount bigint,
  sender_bank_balance bigint,
  recipient_name text,
  transfer_status text,
  scheduled_for timestamptz
)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_sender uuid := auth.uid();
  v_recipient uuid;
  v_recipient_name text;
  v_fee_owner uuid;
  v_fee bigint := 0;
  v_receive bigint;
  v_sender_bank public.online_slot_bank_accounts%rowtype;
  v_recipient_bank public.online_slot_bank_accounts%rowtype;
  v_fee_bank public.online_slot_bank_accounts%rowtype;
  v_match_count integer;
  v_transfer_id bigint;
  v_mode text := lower(coalesce(p_mode, ''));
  v_status text;
  v_due timestamptz;
  v_now timestamptz := now();
  v_max constant bigint := 9000000000000000;
begin
  if v_sender is null then raise exception 'Bitte melde dich erneut an.'; end if;
  if v_mode not in ('instant','delayed') then raise exception 'Bitte wähle eine gültige Überweisungsart.'; end if;
  if p_amount is null or p_amount < 1 or p_amount > v_max then raise exception 'Bitte gib einen gültigen Betrag ein.'; end if;
  if p_pin is null or p_pin !~ '^[0-9]{6}$' then raise exception 'Bitte gib deine sechsstellige Bank-PIN ein.'; end if;
  if p_recipient_name is null or length(trim(p_recipient_name)) < 2 then raise exception 'Bitte gib den Spielernamen des Empfängers ein.'; end if;

  select count(*) into v_match_count
  from public.online_slot_scores as s
  where lower(btrim(s.display_name)) = lower(btrim(p_recipient_name));
  if v_match_count = 0 then raise exception 'Dieser Spielername wurde nicht gefunden. Prüfe die Schreibweise.'; end if;
  if v_match_count > 1 then raise exception 'Dieser Spielername ist nicht eindeutig. Der Empfänger muss einen eindeutigen Spielernamen wählen.'; end if;
  select s.player_id, s.display_name into v_recipient, v_recipient_name
  from public.online_slot_scores as s
  where lower(btrim(s.display_name)) = lower(btrim(p_recipient_name));
  if v_recipient = v_sender then raise exception 'Du kannst keine Coins an dich selbst überweisen.'; end if;

  insert into public.online_slot_bank_accounts(player_id) values (v_sender) on conflict (player_id) do nothing;
  insert into public.online_slot_bank_accounts(player_id) values (v_recipient) on conflict (player_id) do nothing;

  -- Resolve the bank-fee account first, then lock every affected account in one stable order.
  if v_mode = 'instant' then
    select count(*) into v_match_count
    from public.online_slot_scores as s
    where lower(btrim(s.display_name)) = 'kamar303';
    if v_match_count <> 1 then
      raise exception 'Sofortüberweisung ist nicht verfügbar: Es muss genau einen Spieler mit dem Namen Kamar303 geben.';
    end if;
    select s.player_id into v_fee_owner
    from public.online_slot_scores as s
    where lower(btrim(s.display_name)) = 'kamar303';
    insert into public.online_slot_bank_accounts(player_id) values (v_fee_owner) on conflict (player_id) do nothing;
  end if;

  perform b.player_id
  from public.online_slot_bank_accounts as b
  where b.player_id = v_sender or b.player_id = v_recipient or (v_mode = 'instant' and b.player_id = v_fee_owner)
  order by b.player_id
  for update;

  select b.* into v_sender_bank from public.online_slot_bank_accounts as b where b.player_id = v_sender;
  select b.* into v_recipient_bank from public.online_slot_bank_accounts as b where b.player_id = v_recipient;
  if v_sender_bank.bank_pin_hash is null then raise exception 'Richte zuerst im Geldautomaten deine sechsstellige Bank-PIN ein.'; end if;
  if crypt(p_pin, v_sender_bank.bank_pin_hash) <> v_sender_bank.bank_pin_hash then
    raise exception 'Die Bank-PIN ist falsch.';
  end if;
  if p_amount > v_sender_bank.bank_balance then raise exception 'In deiner Bank liegen nicht genug Coins.'; end if;

  if v_mode = 'instant' then
    v_fee := (p_amount * 5) / 100;
    v_receive := p_amount - v_fee;
    select b.* into v_fee_bank from public.online_slot_bank_accounts as b where b.player_id = v_fee_owner;
    if v_fee_owner <> v_sender and v_fee_owner <> v_recipient and v_fee_bank.bank_balance > v_max - v_fee then raise exception 'Das Kamar303-Bankkonto hat sein Coin-Limit erreicht.'; end if;
    if v_recipient = v_fee_owner then
      if v_recipient_bank.bank_balance > v_max - p_amount then raise exception 'Das Bankkonto des Empfängers hat sein Speicherlimit erreicht.'; end if;
    elsif v_recipient_bank.bank_balance > v_max - v_receive then
      raise exception 'Das Bankkonto des Empfängers hat sein Speicherlimit erreicht.';
    end if;

    update public.online_slot_bank_accounts as b
       set bank_balance = b.bank_balance - p_amount,
           updated_at = v_now
     where b.player_id = v_sender
     returning b.* into v_sender_bank;
    update public.online_slot_bank_accounts as b
       set bank_balance = b.bank_balance + v_receive,
           updated_at = v_now
     where b.player_id = v_recipient
     returning b.* into v_recipient_bank;
    if v_fee > 0 then
      update public.online_slot_bank_accounts as b
         set bank_balance = b.bank_balance + v_fee,
             updated_at = v_now
       where b.player_id = v_fee_owner;
    end if;
    v_status := 'completed';
    v_due := v_now;
  else
    v_fee := 0;
    v_receive := p_amount;
    v_due := v_now + interval '1 hour';
    update public.online_slot_bank_accounts as b
       set bank_balance = b.bank_balance - p_amount,
           updated_at = v_now
     where b.player_id = v_sender
     returning b.* into v_sender_bank;
    v_status := 'pending';
  end if;

  insert into public.online_slot_bank_transfers(
    sender_id, recipient_id, gross_amount, recipient_amount, fee_amount,
    transfer_mode, status, created_at, scheduled_for, completed_at
  ) values (
    v_sender, v_recipient, p_amount, v_receive, v_fee,
    v_mode, v_status, v_now, case when v_mode = 'delayed' then v_due else null end,
    case when v_mode = 'instant' then v_now else null end
  ) returning id into v_transfer_id;

  return query
  select v_transfer_id, v_mode, p_amount, v_receive, v_fee,
         v_sender_bank.bank_balance, v_recipient_name, v_status,
         case when v_mode = 'delayed' then v_due else null end;
end;
$$;
revoke all on function public.transfer_slot_bank_to_player(text, bigint, text, text) from public, anon;
grant execute on function public.transfer_slot_bank_to_player(text, bigint, text, text) to authenticated;

-- This worker credits due delayed transfers. It is idempotent and safe for concurrent callers.
create or replace function public.process_due_slot_bank_transfers()
returns integer
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_transfer public.online_slot_bank_transfers%rowtype;
  v_sender public.online_slot_bank_accounts%rowtype;
  v_recipient public.online_slot_bank_accounts%rowtype;
  v_processed integer := 0;
  v_now timestamptz := now();
  v_max constant bigint := 9000000000000000;
begin
  for v_transfer in
    select t.*
    from public.online_slot_bank_transfers as t
    where t.status = 'pending' and t.scheduled_for <= v_now
    order by t.scheduled_for, t.id
    for update skip locked
  loop
    perform b.player_id
    from public.online_slot_bank_accounts as b
    where b.player_id in (v_transfer.sender_id, v_transfer.recipient_id)
    order by b.player_id
    for update;

    select b.* into v_sender from public.online_slot_bank_accounts as b where b.player_id = v_transfer.sender_id;
    select b.* into v_recipient from public.online_slot_bank_accounts as b where b.player_id = v_transfer.recipient_id;

    if v_recipient.bank_balance > v_max - v_transfer.recipient_amount then
      update public.online_slot_bank_accounts as b
         set bank_balance = least(v_max, b.bank_balance + v_transfer.gross_amount), updated_at = v_now
       where b.player_id = v_transfer.sender_id;
      update public.online_slot_bank_transfers as t
         set status = 'refunded', completed_at = v_now
       where t.id = v_transfer.id;
    else
      update public.online_slot_bank_accounts as b
         set bank_balance = b.bank_balance + v_transfer.recipient_amount, updated_at = v_now
       where b.player_id = v_transfer.recipient_id;
      update public.online_slot_bank_transfers as t
         set status = 'completed', completed_at = v_now
       where t.id = v_transfer.id;
    end if;
    v_processed := v_processed + 1;
  end loop;
  return v_processed;
end;
$$;
revoke all on function public.process_due_slot_bank_transfers() from public, anon;
grant execute on function public.process_due_slot_bank_transfers() to authenticated;

-- Expose only transfer records belonging to the current player.
create or replace function public.get_slot_bank_transfers()
returns table(
  transfer_id bigint,
  other_player text,
  direction text,
  amount bigint,
  fee bigint,
  transfer_mode text,
  status text,
  created_at timestamptz,
  scheduled_for timestamptz,
  completed_at timestamptz
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'Bitte melde dich erneut an.'; end if;
  perform public.process_due_slot_bank_transfers();
  return query
    select t.id,
           case when t.sender_id = v_uid then recipient.display_name else sender.display_name end,
           case when t.sender_id = v_uid then 'Ausgehend'::text else 'Eingehend'::text end,
           case when t.sender_id = v_uid then t.gross_amount else t.recipient_amount end,
           t.fee_amount,
           t.transfer_mode,
           t.status,
           t.created_at,
           t.scheduled_for,
           t.completed_at
    from public.online_slot_bank_transfers as t
    left join public.online_slot_scores as sender on sender.player_id = t.sender_id
    left join public.online_slot_scores as recipient on recipient.player_id = t.recipient_id
    where t.sender_id = v_uid or t.recipient_id = v_uid
    order by t.created_at desc, t.id desc
    limit 20;
end;
$$;
revoke all on function public.get_slot_bank_transfers() from public, anon;
grant execute on function public.get_slot_bank_transfers() to authenticated;

-- Best-effort one-minute cron worker. If pg_cron is not enabled on this project,
-- the app processes due transfers whenever any player refreshes the bank.
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    begin
      perform cron.unschedule(jobid)
      from cron.job
      where jobname = 'schreibbot-slot-bank-transfer-worker';
      perform cron.schedule(
        'schreibbot-slot-bank-transfer-worker',
        '* * * * *',
        'select public.process_due_slot_bank_transfers();'
      );
    exception when others then
      raise notice 'pg_cron is installed but the bank worker could not be scheduled; website polling remains available: %', sqlerrm;
    end;
  else
    raise notice 'pg_cron is not enabled. Due transfers will be processed when a bank session refreshes.';
  end if;
end;
$$;

